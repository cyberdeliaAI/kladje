// Collect the license texts of every Rust dependency in Cargo.lock, for all
// platforms, into one file that ships with the application. Reads only the
// package sources Cargo has already downloaded. Run with --check to verify
// that the checked-in file matches the locked dependencies.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const output = "src-tauri/THIRD-PARTY-NOTICES.txt";
const metadata = JSON.parse(
  execFileSync(
    "cargo",
    ["metadata", "--format-version", "1", "--locked", "--manifest-path", "src-tauri/Cargo.toml"],
    { maxBuffer: 64 * 1024 * 1024 },
  ),
);
const crates = metadata.packages
  .filter((pkg) => pkg.source)
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const LICENSE_FILE = /^(licen[sc]e|copying|copyright|notice|unlicense)/i;
const texts = new Map(); // normalised text -> ["name version (file)"]
const index = [];
for (const pkg of crates) {
  const dir = path.dirname(pkg.manifest_path);
  const files = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && LICENSE_FILE.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  const license = pkg.license || "see license file";
  index.push(
    `${pkg.name} ${pkg.version}\n  License: ${license}` +
      (pkg.repository ? `\n  Source: ${pkg.repository}` : "") +
      (files.length ? "" : "\n  This package ships no license file. Its declared license applies."),
  );
  for (const file of files) {
    const full = path.join(dir, file);
    if (fs.statSync(full).size > 256 * 1024) throw Error("Unexpectedly large license file: " + full);
    const text = fs
      .readFileSync(full, "utf8")
      .replace(/\r\n?/g, "\n")
      .replace(/[ \t]+$/gm, "")
      .trim();
    if (!text) continue;
    if (!texts.has(text)) texts.set(text, []);
    texts.get(text).push(`${pkg.name} ${pkg.version} (${file})`);
  }
}

// The syntax definitions and themes compiled into the binary carry their own
// notices, which their packager exposes through an API rather than as files.
const syntaxes = execFileSync(
  "cargo",
  ["run", "--quiet", "--locked", "--manifest-path", "src-tauri/Cargo.toml", "--example", "notices"],
  { encoding: "utf8", maxBuffer: 16 * 1024 * 1024, stdio: ["ignore", "pipe", "inherit"] },
)
  .replace(/\r\n?/g, "\n")
  .replace(/[ \t]+$/gm, "")
  .trim();
if (syntaxes.length < 1000) throw Error("Missing syntax definition acknowledgements");

const rule = "\n" + "-".repeat(78) + "\n";
const sections = [...texts].map(([text, users]) => "Applies to:\n  " + users.join("\n  ") + "\n\n" + text);
const document =
  "Third-party notices for the Rust packages built into Kladje\n\n" +
  "Kladje links the packages listed below. Not every package is part of every\n" +
  "build: the list covers all supported platforms. Packages under the Mozilla\n" +
  "Public License 2.0 are used unmodified; their source is available at the\n" +
  "address given for each. Generated by scripts/build-notices.mjs from\n" +
  "src-tauri/Cargo.lock. Do not edit by hand.\n\n" +
  `${crates.length} packages, ${texts.size} distinct license texts.\n` +
  rule +
  "\nPACKAGES\n\n" +
  index.join("\n\n") +
  "\n" +
  rule +
  "\nLICENSE TEXTS\n" +
  rule +
  "\n" +
  sections.join("\n" + rule + "\n") +
  "\n" +
  rule +
  "\nSYNTAX DEFINITIONS AND COLOUR THEMES\n\n" +
  "Code highlighting uses the definitions and themes below, embedded through\n" +
  "the two-face package.\n\n" +
  syntaxes +
  "\n";

if (process.argv.includes("--check")) {
  const current = fs.existsSync(output) ? fs.readFileSync(output, "utf8") : "";
  if (current !== document) {
    console.error(output + " is out of date. Run: npm run build:notices");
    process.exit(1);
  }
  console.log(output, "matches Cargo.lock:", crates.length, "packages.");
} else {
  fs.writeFileSync(output, document);
  console.log("Wrote", output, "for", crates.length, "packages and", texts.size, "license texts.");
}
