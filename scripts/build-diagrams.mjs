// Put the Mermaid engine where the application can load it and list the
// licences of everything that bundle contains. Both are generated from
// node_modules. The engine is not checked in; the notices are, because the
// bundle configuration ships them. Tauri runs this before a build.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const modules = path.join(root, "node_modules");
const engine = path.join(modules, "mermaid/dist/mermaid.min.js");
if (!fs.existsSync(engine)) throw Error("Mermaid is not installed. Run npm ci first.");
const vendor = path.join(root, "ui/vendor");

const write = (name, content) => {
  const file = path.join(vendor, name);
  if (fs.existsSync(file) && fs.readFileSync(file).equals(Buffer.from(content))) return false;
  fs.writeFileSync(file, content);
  return true;
};

// Follow the packages Mermaid depends on at run time, as Node resolves them.
function locate(from, name) {
  for (let dir = from; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, "node_modules", name);
    if (fs.existsSync(path.join(candidate, "package.json"))) return candidate;
    if (dir === path.dirname(dir) || dir === root) break;
  }
  const top = path.join(modules, name);
  if (fs.existsSync(path.join(top, "package.json"))) return top;
  throw Error(`Cannot find ${name}, needed by ${from}`);
}
const packages = new Map();
const pending = [path.join(modules, "mermaid")];
while (pending.length) {
  const dir = pending.pop();
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  const id = `${manifest.name} ${manifest.version}`;
  if (packages.has(id)) continue;
  packages.set(id, { dir, license: manifest.license || "see license file", source: manifest.repository?.url || manifest.homepage || "" });
  for (const name of Object.keys(manifest.dependencies || {})) pending.push(locate(dir, name));
}

const LICENSE_FILE = /^(licen[sc]e|copying|notice)/i;
const texts = new Map();
const index = [];
for (const id of [...packages.keys()].sort()) {
  const { dir, license, source } = packages.get(id);
  const files = fs.readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && LICENSE_FILE.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  index.push(`${id}\n  License: ${license}` + (source ? `\n  Source: ${source.replace(/^git\+/, "")}` : "") +
    (files.length ? "" : "\n  This package ships no license file. Its declared license applies."));
  for (const file of files) {
    const text = fs.readFileSync(path.join(dir, file), "utf8").replace(/\r\n?/g, "\n").replace(/[ \t]+$/gm, "").trim();
    if (!text) continue;
    if (!texts.has(text)) texts.set(text, []);
    texts.get(text).push(`${id} (${file})`);
  }
}
const rule = "\n" + "-".repeat(78) + "\n";
const notices =
  "Third-party notices for the diagram engine built into Kladje\n\n" +
  "Diagrams are drawn by Mermaid. Its bundle, ui/vendor/mermaid.min.js, contains\n" +
  "the packages listed below. Generated by scripts/build-diagrams.mjs from\n" +
  "package-lock.json. Do not edit by hand.\n\n" +
  `${packages.size} packages, ${texts.size} distinct license texts.\n` + rule + "\nPACKAGES\n\n" + index.join("\n\n") + "\n" + rule +
  "\nLICENSE TEXTS\n" + rule + "\n" +
  [...texts].map(([text, users]) => "Applies to:\n  " + users.join("\n  ") + "\n\n" + text).join("\n" + rule + "\n") + "\n";

// The notices are checked in, so a native build finds them even before this
// script runs. --check verifies them against the installed packages.
if (process.argv.includes("--check")) {
  const file = path.join(vendor, "THIRD-PARTY-NOTICES-DIAGRAMS.txt");
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== notices) {
    console.error("ui/vendor/THIRD-PARTY-NOTICES-DIAGRAMS.txt is out of date. Run: npm run build:diagrams");
    process.exit(1);
  }
  console.log("ui/vendor/THIRD-PARTY-NOTICES-DIAGRAMS.txt matches package-lock.json:", packages.size, "packages.");
  process.exit(0);
}
const changed = [write("mermaid.min.js", fs.readFileSync(engine)), write("THIRD-PARTY-NOTICES-DIAGRAMS.txt", notices)];
console.log(changed.some(Boolean) ? "Updated" : "Up to date:", "ui/vendor/mermaid.min.js and its notices for", packages.size, "packages.");
